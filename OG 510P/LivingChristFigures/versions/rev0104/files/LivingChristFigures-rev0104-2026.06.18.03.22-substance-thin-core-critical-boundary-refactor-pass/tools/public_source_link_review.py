#!/usr/bin/env python3
from __future__ import annotations
import argparse, csv, json
from pathlib import Path

FIELDS=['source_id','domain','source_type','candidate_ids','harm_proximity','public_link_policy','public_url_release_decision','required_boundary_note','allowed_public_use','reason','date_reviewed']
ALLOWED_DECISIONS={'block_public_url','manual_review_required_block_until_review','allow_only_with_boundary_note_after_manual_review','allow_after_context_review'}
REVIEW_DATE='2026-06-13'
NEAR_HARM_TOKENS=('contact_path_near','case_detail_near','testimony_near','family_profile_near','image_or_vigil_near','operational_route_near','shelter_location_near','support_path_near')

def read_csv(path: Path):
    if not path.exists(): return []
    with path.open(encoding='utf-8', newline='') as f: return list(csv.DictReader(f))

def write_csv(path: Path, rows, fields):
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open('w',encoding='utf-8',newline='') as f:
        w=csv.DictWriter(f, fieldnames=fields); w.writeheader(); w.writerows([{k:r.get(k,'') for k in fields} for r in rows])

def write_json(path: Path, rows): path.write_text(json.dumps(rows,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')

def write_md(path: Path, rows):
    lines=['# Public Source Link Review — current','',
           'Generated by `tools/public_source_link_review.py`. This report is a URL-exposure gate: it reviews whether a source URL may be exposed in public material. A URL can remain useful internally while remaining blocked publicly.',
           '',f'Rows: {len(rows)}','']
    fields=['source_id','domain','public_link_policy','public_url_release_decision','required_boundary_note','allowed_public_use','reason']
    lines.append('| '+' | '.join(fields)+' |'); lines.append('| '+' | '.join(['---']*len(fields))+' |')
    for r in rows[:120]:
        lines.append('| '+' | '.join(str(r.get(f,'')).replace('|','/').replace('\n',' ')[:220] for f in fields)+' |')
    if len(rows)>120: lines.append('\n_Table truncated at 120 rows; CSV/JSON contain all rows._')
    path.write_text('\n'.join(lines)+'\n',encoding='utf-8')

def decision_for(row: dict) -> dict:
    policy=(row.get('public_link_policy') or '').strip()
    harm=row.get('harm_proximity','')
    if policy.startswith('internal_only'):
        decision='block_public_url'
        note='Public URL blocked: source is near contact, case, testimony, image, route, event, or other harm-proximate surfaces.'
        allowed='internal evidence only; no public URL'
    elif policy=='boundary_note_required_or_internal_only':
        decision='manual_review_required_block_until_review'
        note='Blocked until a source-specific reviewer decides whether a boundary note is sufficient.'
        allowed='internal evidence or manually reviewed boundary reference only'
    elif policy in {'boundary_note_required','public_link_allowed_with_boundary_note'}:
        decision='allow_only_with_boundary_note_after_manual_review'
        note='URL may be exposed only after manual review and with no-referral/no-completion/no-extraction boundary text.'
        allowed='context link only after manual review; no contact/case/route/capacity use'
    elif policy=='public_link_allowed':
        decision='allow_after_context_review'
        note='No automatic release; reviewer must still confirm context and public prose shape.'
        allowed='context link after review'
    else:
        decision='manual_review_required_block_until_review'
        note='Unknown or missing public_link_policy; fail closed.'
        allowed='internal evidence only until policy is repaired'
    if any(token in harm for token in NEAR_HARM_TOKENS):
        if decision=='allow_after_context_review':
            decision='allow_only_with_boundary_note_after_manual_review'
            note += ' Near-harm source requires boundary note.'
            allowed='context link only after manual review; no extraction'
    return {
        'source_id':row.get('source_id',''),
        'domain':row.get('domain',''),
        'source_type':row.get('source_type',''),
        'candidate_ids':row.get('candidate_ids',''),
        'harm_proximity':harm,
        'public_link_policy':policy,
        'public_url_release_decision':decision,
        'required_boundary_note':note,
        'allowed_public_use':allowed,
        'reason':row.get('risk_notes','') or row.get('does_not_support','') or 'derived from public_link_policy and harm_proximity',
        'date_reviewed':REVIEW_DATE,
    }

def run(root: Path):
    return [decision_for(r) for r in read_csv(root/'Source-Registry-current.csv')]

def write_reports(root: Path, rows):
    out=root/'META'
    write_csv(out/'Public-Source-Link-Review-current.csv', rows, FIELDS)
    write_json(out/'Public-Source-Link-Review-current.json', rows)
    write_md(out/'Public-Source-Link-Review-current.md', rows)

def main():
    ap=argparse.ArgumentParser(); ap.add_argument('root', nargs='?', default='.'); ap.add_argument('--write-report', action='store_true'); ap.add_argument('--json', action='store_true')
    args=ap.parse_args(); root=Path(args.root).resolve(); rows=run(root)
    if args.write_report: write_reports(root, rows)
    if args.json: print(json.dumps(rows, ensure_ascii=False, indent=2))
    else:
        counts={}
        for r in rows: counts[r['public_url_release_decision']]=counts.get(r['public_url_release_decision'],0)+1
        print('public_source_link_review_rows='+str(len(rows))+' '+' '.join(f'{k}={v}' for k,v in sorted(counts.items())))
if __name__=='__main__': main()
