#!/usr/bin/env python3
from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
PATCHSET_PATCH = ROOT / 'artifacts' / 'patches' / 'rust_external_test_patchset.patch'
BUNDLE_REPORT = ROOT / 'artifacts' / 'reports' / 'rust_standing_bootstrap_post_patchset_bundle.json'
BUNDLE_PATCH = ROOT / 'artifacts' / 'patches' / 'rust_standing_bootstrap_post_patchset_bundle.patch'
OUT_JSON = ROOT / 'artifacts' / 'reports' / 'rust_standing_bootstrap_post_patchset_bundle_rehearsal.json'
OUT_MD = ROOT / 'docs' / 'RUST_STANDING_BOOTSTRAP_POST_PATCHSET_BUNDLE_REHEARSAL.md'


def _sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _run_apply(cwd: Path, patch_path: Path, check_only: bool) -> tuple[bool, str]:
    cmd = ['git', 'apply']
    if check_only:
        cmd.append('--check')
    cmd.append(str(patch_path))
    proc = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True)
    summary = '\n'.join(part for part in [proc.stdout.strip(), proc.stderr.strip()] if part).strip()
    return proc.returncode == 0, summary


def _snapshot_hashes(root: Path, relpaths: list[str]) -> dict[str, str]:
    out: dict[str, str] = {}
    for rel in relpaths:
        path = root / rel
        out[rel] = _sha256_bytes(path.read_bytes()) if path.exists() else 'MISSING'
    return out


def collect() -> dict[str, Any]:
    bundle_report = json.loads(BUNDLE_REPORT.read_text(encoding='utf-8'))
    patchset_text = PATCHSET_PATCH.read_text(encoding='utf-8')
    bundle_text = BUNDLE_PATCH.read_text(encoding='utf-8')
    target_files = [str(rel) for rel in bundle_report['target_files']]
    expected_hashes = {str(rel): str(digest) for rel, digest in bundle_report['final_hashes'].items()}

    with tempfile.TemporaryDirectory(prefix='gr_bootstrap_post_patchset_bundle_rehearsal_') as tmp:
        scratch = Path(tmp)
        patchset_dst = scratch / PATCHSET_PATCH.relative_to(ROOT)
        patchset_dst.parent.mkdir(parents=True, exist_ok=True)
        patchset_dst.write_text(patchset_text, encoding='utf-8')
        bundle_dst = scratch / BUNDLE_PATCH.relative_to(ROOT)
        bundle_dst.parent.mkdir(parents=True, exist_ok=True)
        bundle_dst.write_text(bundle_text, encoding='utf-8')
        for rel in target_files:
            src = ROOT / rel
            if src.exists():
                dst = scratch / rel
                dst.parent.mkdir(parents=True, exist_ok=True)
                dst.write_bytes(src.read_bytes())

        patchset_check_ok, patchset_check_summary = _run_apply(scratch, patchset_dst, True)
        patchset_apply_ok = False
        patchset_apply_summary = ''
        if patchset_check_ok:
            patchset_apply_ok, patchset_apply_summary = _run_apply(scratch, patchset_dst, False)

        bundle_check_ok = False
        bundle_check_summary = ''
        bundle_apply_ok = False
        bundle_apply_summary = ''
        final_hashes: dict[str, str] = {rel: 'MISSING' for rel in target_files}
        if patchset_check_ok and patchset_apply_ok:
            bundle_check_ok, bundle_check_summary = _run_apply(scratch, bundle_dst, True)
            if bundle_check_ok:
                bundle_apply_ok, bundle_apply_summary = _run_apply(scratch, bundle_dst, False)
                final_hashes = _snapshot_hashes(scratch, target_files)

    return {
        'tool': 'build_rust_standing_bootstrap_post_patchset_bundle_rehearsal',
        'source_patchset_patch': str(PATCHSET_PATCH.relative_to(ROOT)),
        'source_bundle_report': str(BUNDLE_REPORT.relative_to(ROOT)),
        'source_bundle_patch': str(BUNDLE_PATCH.relative_to(ROOT)),
        'target_files': target_files,
        'summary': {
            'patchset_check_ok': patchset_check_ok,
            'patchset_apply_ok': patchset_apply_ok,
            'bundle_check_ok': bundle_check_ok,
            'bundle_apply_ok': bundle_apply_ok,
            'final_hashes_match_report': final_hashes == expected_hashes,
            'bundle_patch_sha256': _sha256_bytes(bundle_text.encode('utf-8')),
        },
        'notes': {
            'patchset_check_summary': patchset_check_summary,
            'patchset_apply_summary': patchset_apply_summary,
            'bundle_check_summary': bundle_check_summary,
            'bundle_apply_summary': bundle_apply_summary,
        },
    }


def render_markdown(report: dict[str, Any]) -> str:
    s = report['summary']
    lines = [
        '# Rust Standing Bootstrap Post-Patchset Bundle Rehearsal',
        '',
        'Generated by `scripts/report/build_rust_standing_bootstrap_post_patchset_bundle_rehearsal.py`. This scratch-applies the monolithic comeback patchset first, then applies the post-patchset bootstrap convenience bundle, and checks that the landed file hashes match the generated bundle report.',
        '',
        '## Snapshot',
        '',
        f"- source patchset patch: `{report['source_patchset_patch']}`",
        f"- source bundle patch: `{report['source_bundle_patch']}`",
        f"- patchset_check_ok: `{str(s['patchset_check_ok']).lower()}`",
        f"- patchset_apply_ok: `{str(s['patchset_apply_ok']).lower()}`",
        f"- bundle_check_ok: `{str(s['bundle_check_ok']).lower()}`",
        f"- bundle_apply_ok: `{str(s['bundle_apply_ok']).lower()}`",
        f"- final_hashes_match_report: `{str(s['final_hashes_match_report']).lower()}`",
        f"- bundle_patch_sha256: `{s['bundle_patch_sha256']}`",
        '',
    ]
    return '\n'.join(lines)


def _check(expected_report: dict[str, Any], expected_markdown: str) -> int:
    if not OUT_JSON.exists() or not OUT_MD.exists():
        print('rust-standing-bootstrap-post-patchset-bundle-rehearsal: missing report/doc', file=sys.stderr)
        return 1
    if json.loads(OUT_JSON.read_text(encoding='utf-8')) != expected_report:
        print('rust-standing-bootstrap-post-patchset-bundle-rehearsal: report drift detected', file=sys.stderr)
        return 1
    if OUT_MD.read_text(encoding='utf-8').rstrip('\n') != expected_markdown.rstrip('\n'):
        print('rust-standing-bootstrap-post-patchset-bundle-rehearsal: markdown drift detected', file=sys.stderr)
        return 1
    print('rust-standing-bootstrap-post-patchset-bundle-rehearsal: ok patchset baseline plus bundle lands and matches report hashes')
    return 0


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    report = collect()
    markdown = render_markdown(report)
    if args.write:
        OUT_JSON.parent.mkdir(parents=True, exist_ok=True)
        OUT_JSON.write_text(json.dumps(report, indent=2, sort_keys=True) + '\n', encoding='utf-8')
        OUT_MD.write_text(markdown + '\n', encoding='utf-8')
        print(f'wrote {OUT_JSON.relative_to(ROOT)}')
        print(f'wrote {OUT_MD.relative_to(ROOT)}')
        return 0
    return _check(report, markdown)


if __name__ == '__main__':
    raise SystemExit(main())
