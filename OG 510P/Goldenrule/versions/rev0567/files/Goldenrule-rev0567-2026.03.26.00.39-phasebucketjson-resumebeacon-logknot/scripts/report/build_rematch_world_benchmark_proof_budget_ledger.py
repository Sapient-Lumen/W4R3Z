#!/usr/bin/env python3
from __future__ import annotations

import hashlib
import json
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
CITATION_MATRIX_REPORT = ROOT / 'artifacts' / 'reports' / 'rematch_world_benchmark_citation_witness_matrix.json'
CLAIM_FRONTIER_REPORT = ROOT / 'artifacts' / 'reports' / 'rematch_world_benchmark_claim_frontier.json'
OUT_JSON = ROOT / 'artifacts' / 'reports' / 'rematch_world_benchmark_proof_budget_ledger.json'
OUT_MD = ROOT / 'docs' / 'REMATCH_WORLD_BENCHMARK_PROOF_BUDGET_LEDGER.md'

TITLE = '# Rematch-world benchmark proof-budget ledger'
SUBTITLE = (
    'Generated byte-budget ledger for the first endogenous rematch-world benchmark. '
    'Use it to keep the archive citation-first and small: each claim family now carries one exact minimal proof bundle, '
    'its byte cost, its reuse profile, and the smallest unique surface library needed to support all eight claim families.'
)


def load_json(path: Path) -> Any:
    return json.loads(path.read_text(encoding='utf-8'))


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open('rb') as fh:
        for chunk in iter(lambda: fh.read(65536), b''):
            h.update(chunk)
    return h.hexdigest()


def surface_kind(path: str) -> str:
    if path.startswith('docs/'):
        return 'generated_doc'
    if path.startswith('examples/snapshots/'):
        return 'receipt_snapshot'
    if path.startswith('artifacts/reports/'):
        return 'generated_report'
    return 'repo_surface'


def frontier_label(frontier_kind: str) -> str:
    if frontier_kind == 'safe_to_cite_now':
        return 'safe_now'
    if frontier_kind == 'native_stage_unlock':
        return 'native_frontier'
    if frontier_kind == 'blocked_by_engine_gap':
        return 'engine_gap'
    return frontier_kind


def build_report() -> dict[str, Any]:
    for path in [CITATION_MATRIX_REPORT, CLAIM_FRONTIER_REPORT]:
        if not path.exists():
            raise RuntimeError(f'missing required input: {path.relative_to(ROOT)}')

    citation = load_json(CITATION_MATRIX_REPORT)
    frontier = load_json(CLAIM_FRONTIER_REPORT)
    frontier_rows = {row['claim_family_id']: row for row in frontier['frontier_rows']}
    claim_rows = citation['claim_family_rows']

    bundle_rows: list[dict[str, Any]] = []
    surface_usage: dict[str, dict[str, Any]] = {}
    posture_bytes: dict[str, int] = {}
    frontier_bytes: dict[str, int] = {}

    for row in claim_rows:
        claim_id = row['claim_family_id']
        frontier_row = frontier_rows[claim_id]
        paths = row['minimal_citation_paths']
        component_rows = []
        bundle_bytes = 0
        docs_only = True
        for rel in paths:
            path = ROOT / rel
            if not path.exists():
                raise RuntimeError(f'missing cited surface: {rel}')
            raw_bytes = path.stat().st_size
            digest = sha256_file(path)
            kind = surface_kind(rel)
            if kind != 'generated_doc':
                docs_only = False
            component_rows.append({
                'path': rel,
                'surface_kind': kind,
                'raw_bytes': raw_bytes,
                'sha256': digest,
            })
            bundle_bytes += raw_bytes
            usage = surface_usage.setdefault(rel, {
                'path': rel,
                'surface_kind': kind,
                'raw_bytes': raw_bytes,
                'sha256': digest,
                'claim_family_ids': [],
                'claim_family_count': 0,
            })
            if usage['raw_bytes'] != raw_bytes or usage['sha256'] != digest:
                raise RuntimeError(f'surface drifted during proof-budget build: {rel}')
            usage['claim_family_ids'].append(claim_id)
        for usage in component_rows:
            pass
        for rel in paths:
            surface_usage[rel]['claim_family_count'] += 1
        posture_bytes[row['posture']] = posture_bytes.get(row['posture'], 0) + bundle_bytes
        frontier_bytes[frontier_label(frontier_row['frontier_kind'])] = frontier_bytes.get(frontier_label(frontier_row['frontier_kind']), 0) + bundle_bytes
        bundle_rows.append({
            'claim_family_id': claim_id,
            'claim_label': row['claim_label'],
            'posture': row['posture'],
            'frontier_kind': frontier_row['frontier_kind'],
            'frontier_bucket': frontier_label(frontier_row['frontier_kind']),
            'bundle_surface_count': len(component_rows),
            'bundle_bytes': bundle_bytes,
            'docs_only_bundle': docs_only,
            'includes_receipt_snapshot': any(item['surface_kind'] == 'receipt_snapshot' for item in component_rows),
            'open_spec_count': len(row['open_spec_ids']),
            'minimal_citation_paths': paths,
            'component_rows': component_rows,
            'why_it_matters': row['why_it_matters'],
        })

    if len(bundle_rows) != 8:
        raise RuntimeError(f'expected 8 proof-budget rows, found {len(bundle_rows)}')

    unique_surface_rows = sorted(surface_usage.values(), key=lambda item: (-item['claim_family_count'], item['path']))
    for row in unique_surface_rows:
        row['claim_family_ids'] = sorted(row['claim_family_ids'])

    smallest_bundle = min(bundle_rows, key=lambda item: (item['bundle_bytes'], item['claim_family_id']))
    largest_bundle = max(bundle_rows, key=lambda item: (item['bundle_bytes'], item['claim_family_id']))
    most_reused_surface = max(unique_surface_rows, key=lambda item: (item['claim_family_count'], -item['raw_bytes'], item['path']))
    unique_surface_byte_total = sum(item['raw_bytes'] for item in unique_surface_rows)
    total_bundle_bytes = sum(item['bundle_bytes'] for item in bundle_rows)

    posture_rows = [{
        'posture': posture,
        'claim_family_count': sum(1 for item in bundle_rows if item['posture'] == posture),
        'total_bundle_bytes': posture_bytes.get(posture, 0),
        'average_bundle_bytes': round(posture_bytes.get(posture, 0) / max(1, sum(1 for item in bundle_rows if item['posture'] == posture)), 2),
    } for posture in ['bridge_ready', 'provisional_interpretation', 'final_authority']]
    frontier_rows_summary = [{
        'frontier_bucket': bucket,
        'claim_family_count': sum(1 for item in bundle_rows if item['frontier_bucket'] == bucket),
        'total_bundle_bytes': frontier_bytes.get(bucket, 0),
    } for bucket in ['safe_now', 'native_frontier', 'engine_gap']]

    main_findings = [
        f"All eight rematch-world claim families can be supported by a unique proof library of just {len(unique_surface_rows)} surfaces totaling {unique_surface_byte_total} bytes.",
        f"The smallest minimal bundle is {smallest_bundle['claim_family_id']} at {smallest_bundle['bundle_bytes']} bytes, while the largest is {largest_bundle['claim_family_id']} at {largest_bundle['bundle_bytes']} bytes; both stay tiny enough to cite directly instead of reopening broad artifacts.",
        f"Exactly {sum(1 for item in bundle_rows if item['docs_only_bundle'])} claim families are docs-only, and only {sum(1 for item in bundle_rows if item['includes_receipt_snapshot'])} need a retained receipt snapshot at all.",
        f"`{most_reused_surface['path']}` is the dominant reusable anchor: it supports {most_reused_surface['claim_family_count']} claim families by itself, so future byte-saving passes should protect it before retaining any larger scratch family.",
    ]

    return {
        'analysis_script': Path(__file__).relative_to(ROOT).as_posix(),
        'focus': 'budget the smallest evidence-backed proof bundles for each first-publication rematch-world claim family so the archive can stay citation-first and size-aware',
        'counts': {
            'claim_family_count': len(bundle_rows),
            'unique_surface_count': len(unique_surface_rows),
            'unique_surface_byte_total': unique_surface_byte_total,
            'total_bundle_bytes': total_bundle_bytes,
            'docs_only_bundle_count': sum(1 for item in bundle_rows if item['docs_only_bundle']),
            'receipt_backed_bundle_count': sum(1 for item in bundle_rows if item['includes_receipt_snapshot']),
            'smallest_bundle_bytes': smallest_bundle['bundle_bytes'],
            'largest_bundle_bytes': largest_bundle['bundle_bytes'],
        },
        'main_findings': main_findings,
        'posture_rows': posture_rows,
        'frontier_rows': frontier_rows_summary,
        'smallest_bundle': {
            'claim_family_id': smallest_bundle['claim_family_id'],
            'bundle_bytes': smallest_bundle['bundle_bytes'],
            'minimal_citation_paths': smallest_bundle['minimal_citation_paths'],
        },
        'largest_bundle': {
            'claim_family_id': largest_bundle['claim_family_id'],
            'bundle_bytes': largest_bundle['bundle_bytes'],
            'minimal_citation_paths': largest_bundle['minimal_citation_paths'],
        },
        'most_reused_surface': {
            'path': most_reused_surface['path'],
            'claim_family_count': most_reused_surface['claim_family_count'],
            'raw_bytes': most_reused_surface['raw_bytes'],
            'claim_family_ids': most_reused_surface['claim_family_ids'],
        },
        'unique_surface_rows': unique_surface_rows,
        'bundle_rows': sorted(bundle_rows, key=lambda item: (item['bundle_bytes'], item['claim_family_id'])),
        'recommended_next_move': 'Use this ledger before adding any new rematch-world scratch: if a claim can already be supported by one of these existing small bundles, cite the named files directly instead of retaining a fresh derived artifact.',
    }


def render(report: dict[str, Any]) -> str:
    counts = report['counts']
    lines = [TITLE, '', f"Focus: {report['focus']}", '', SUBTITLE, '', '## Main findings', '']
    lines.extend(f'- {item}' for item in report['main_findings'])
    lines.extend(['', '## Counts', ''])
    for key in ['claim_family_count', 'unique_surface_count', 'unique_surface_byte_total', 'total_bundle_bytes', 'docs_only_bundle_count', 'receipt_backed_bundle_count', 'smallest_bundle_bytes', 'largest_bundle_bytes']:
        lines.append(f'- {key}: {counts[key]}')
    lines.extend(['', '## Posture budgets', '', '| posture | claim_family_count | total_bundle_bytes | average_bundle_bytes |', '|---|---:|---:|---:|'])
    for row in report['posture_rows']:
        lines.append(f"| `{row['posture']}` | {row['claim_family_count']} | {row['total_bundle_bytes']} | {row['average_bundle_bytes']} |")
    lines.extend(['', '## Frontier budgets', '', '| frontier_bucket | claim_family_count | total_bundle_bytes |', '|---|---:|---:|'])
    for row in report['frontier_rows']:
        lines.append(f"| `{row['frontier_bucket']}` | {row['claim_family_count']} | {row['total_bundle_bytes']} |")
    lines.extend(['', '## Unique proof library', '', '| path | kind | bytes | claim_families |', '|---|---|---:|---|'])
    for row in report['unique_surface_rows']:
        claims = ', '.join(f"`{x}`" for x in row['claim_family_ids'])
        lines.append(f"| `{row['path']}` | `{row['surface_kind']}` | {row['raw_bytes']} | {claims} |")
    lines.extend(['', '## Claim-family bundle matrix', '', '| claim_family_id | posture | frontier_bucket | bundle_bytes | docs_only | receipt_snapshot | paths |', '|---|---|---|---:|---|---|---|'])
    for row in report['bundle_rows']:
        paths = ', '.join(f"`{p}`" for p in row['minimal_citation_paths'])
        lines.append(f"| `{row['claim_family_id']}` | `{row['posture']}` | `{row['frontier_bucket']}` | {row['bundle_bytes']} | {'yes' if row['docs_only_bundle'] else 'no'} | {'yes' if row['includes_receipt_snapshot'] else 'no'} | {paths} |")
    lines.extend(['', '## Claim-family bundle details', ''])
    for row in report['bundle_rows']:
        lines.extend([
            f"### {row['claim_family_id']} — {row['claim_label']}",
            '',
            f"- posture: `{row['posture']}`",
            f"- frontier_kind: `{row['frontier_kind']}`",
            f"- bundle_bytes: {row['bundle_bytes']}",
            f"- bundle_surface_count: {row['bundle_surface_count']}",
            f"- docs_only_bundle: {'yes' if row['docs_only_bundle'] else 'no'}",
            f"- includes_receipt_snapshot: {'yes' if row['includes_receipt_snapshot'] else 'no'}",
            f"- open_spec_count: {row['open_spec_count']}",
            f"- minimal_citation_paths: {', '.join(f'`{p}`' for p in row['minimal_citation_paths'])}",
            f"- why_it_matters: {row['why_it_matters']}",
            '',
        ])
    lines.extend(['## Recommended next move', '', f"- {report['recommended_next_move']}", ''])
    return '\n'.join(lines)


def main() -> int:
    report = build_report()
    OUT_JSON.write_text(json.dumps(report, indent=2) + '\n', encoding='utf-8')
    OUT_MD.write_text(render(report), encoding='utf-8')
    print(f'wrote {OUT_JSON.relative_to(ROOT)} and {OUT_MD.relative_to(ROOT)}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
