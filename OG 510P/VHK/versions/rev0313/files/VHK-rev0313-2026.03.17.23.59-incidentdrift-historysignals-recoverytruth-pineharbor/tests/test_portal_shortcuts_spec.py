def test_portal_hotkeys_can_consume_generated_catalog(monkeypatch, tmp_path: Path) -> None:
    project_dir = _make_project(tmp_path)
    catalog_path = tmp_path / "vhk.portal-shortcuts.yml"

    gen_res = runner.invoke(
        app,
        [
            "gen-portal-shortcuts-spec",
            str(project_dir),
            "--bus-event",
            "vhk.trigger",
            "--out",
            str(catalog_path),
        ],
    )
    assert gen_res.exit_code == 0, gen_res.output

    bound_specs: list[object] = []
    emitted: list[tuple[str, str, dict]] = []

    monkeypatch.setattr(cli_mod, "portal_create_session", lambda: "/org/freedesktop/portal/desktop/session/1_2/vhk")
    monkeypatch.setattr(cli_mod, "portal_bind_shortcuts", lambda sess, specs, parent_window="": bound_specs.extend(specs))
    monkeypatch.setattr(
        cli_mod,
        "iter_portal_shortcut_signals",
        lambda session_handle: iter([
            ShortcutSignal(
                kind="Activated",
                session_handle=session_handle,
                shortcut_id="launch_hotkey",
                timestamp=12345,
                options={},
            )
        ]),
    )
    monkeypatch.setattr(cli_mod, "emit_bus_event", lambda sock, event, payload: emitted.append((sock, event, dict(payload))))
    monkeypatch.setattr(cli_mod, "get_bus_socket_path", lambda root_dir, configured=None: "/tmp/vhk.sock")

    res = runner.invoke(
        app,
        [
            "portal-hotkeys",
            str(project_dir),
            "--catalog",
            str(catalog_path),
            "--bind",
            "--max-events",
            "1",
        ],
    )
    assert res.exit_code == 0, res.output
    assert "Shortcut source:" in res.output
    assert "catalog" in res.output

    assert len(bound_specs) == 1
    assert bound_specs[0].shortcut_id == "launch_hotkey"
    assert bound_specs[0].preferred_trigger == "LOGO+SHIFT+p"

    assert len(emitted) == 1
    sock, event_name, payload = emitted[0]
    assert sock == "/tmp/vhk.sock"
    assert event_name == "vhk.trigger"
    assert payload["portal_kind"] == "Activated"
    assert payload["portal_session"] == "/org/freedesktop/portal/desktop/session/1_2/vhk"
    assert payload["portal_timestamp"] == 12345
    assert payload["shortcut_id"] == "launch_hotkey"
    assert payload["macro"] == "launch"
    assert payload["vars"] == {"mode": "fast"}
    assert payload["binding"] == "launch_hotkey"
    assert payload["keys"] == "Mod4+Shift+P"
    assert payload["require_window"]["class"] == "Firefox"


