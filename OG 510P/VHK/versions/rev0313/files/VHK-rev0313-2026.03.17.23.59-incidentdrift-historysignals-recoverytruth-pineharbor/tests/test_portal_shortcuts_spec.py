runner = CliRunner()


def _make_project(tmp_path: Path) -> Path:
    project_dir = tmp_path / "proj"
    (project_dir / "macros").mkdir(parents=True)

    (project_dir / "macros" / "launch.yaml").write_text(
        yaml.safe_dump(
            {
                "name": "launch",
                "steps": [
                    {"type": "TypeText", "text": "hello"},
                    {"type": "Return", "value": "ok"},
                ],
            },
            sort_keys=False,
        )
    )

    (project_dir / "project.yaml").write_text(
        yaml.safe_dump(
            {
                "name": "proj",
                "settings": {"desktop_backend": "wayland"},
                "bindings": [
                    {
                        "keys": "Mod4+Shift+P",
                        "name": "launch_hotkey",
                        "macro": "launch",
                        "description": "Launch macro",
                        "vars": {"mode": "fast"},
                        "when": {"class": "Firefox"},
                    },
                    {
                        "keys": "Ctrl+ä",
                        "macro": "launch",
                        "description": "Unportable chord",
                    },
                ],
            },
            sort_keys=False,
        )
    )
    return project_dir



def test_gen_portal_shortcuts_spec_writes_reviewable_catalog(tmp_path: Path) -> None:
    project_dir = _make_project(tmp_path)
    out_path = tmp_path / "vhk.portal-shortcuts.yml"

    res = runner.invoke(
        app,
        [
            "gen-portal-shortcuts-spec",
            str(project_dir),
            "--bus-event",
            "vhk.trigger",
            "--out",
            str(out_path),
        ],
    )
    assert res.exit_code == 0, res.output

    text = out_path.read_text()
    assert text.startswith("# VHK portal shortcut catalog for project: proj\n")
    assert "# Generated by: vhk gen-portal-shortcuts-spec" in text

    payload = yaml.safe_load(text)
    assert payload["portal_interface"] == "org.freedesktop.portal.GlobalShortcuts"
    assert payload["bus_event"] == "vhk.trigger"
    assert payload["project"]["desktop_backend"] == "wayland"
    assert payload["bind_command"].startswith("vhk portal-hotkeys ")

    shortcuts = payload["shortcuts"]
    assert len(shortcuts) == 1
    assert shortcuts[0]["shortcut_id"] == "launch_hotkey"
    assert shortcuts[0]["preferred_trigger"] == "LOGO+SHIFT+p"
    assert shortcuts[0]["dispatch_payload"]["macro"] == "launch"
    assert shortcuts[0]["dispatch_payload"]["require_window"]["class"] == "Firefox"

    skipped = payload["skipped_bindings"]
    assert len(skipped) == 1
    assert skipped[0]["description"] == "Unportable chord"
    assert "could not convert hotkey" in skipped[0]["reason"]


